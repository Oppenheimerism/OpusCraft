// Widths are 1..7 px; the engine advances by width + 1 and draws a shadow at
// (+1,+1) with 25% brightness, like vanilla.
//
// Glyphs are written as 8 space-separated rows ('#' = ink, '.' = empty) and
// validated when the module loads.

