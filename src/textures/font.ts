function build(src: Record<string, string>): FontData {
  const glyphs: Record<string, string[]> = {};
  for (const [ch, def] of Object.entries(src)) {
    const rows = def.trim().split(/\s+/);
    if (rows.length !== 8) throw new Error(`font: glyph '${ch}' has ${rows.length} rows`);
    const w = rows[0].length;
    if (w < 1 || w > 7) throw new Error(`font: glyph '${ch}' has width ${w}`);
    for (const r of rows) {
      if (r.length !== w) throw new Error(`font: glyph '${ch}' has ragged rows`);
      if (!/^[#.]+$/.test(r)) throw new Error(`font: glyph '${ch}' has bad chars`);
    }
    glyphs[ch] = rows;
  }
  return { height: 8, ascent: 7, glyphs };
}

export const FONT: FontData = build(SRC);

/** Width in px of a glyph (without the 1 px spacing); unknown chars fall back to '?'. */
export function glyphWidth(ch: string): number {
  const g = FONT.glyphs[ch] ?? FONT.glyphs['?'];
  return g[0].length;
}

/** Advance-based width of a string, as the engine lays it out (no shadow). */
export function textWidth(s: string): number {
  let w = 0;
  for (const ch of s) w += glyphWidth(ch) + 1;
  return w;
}
